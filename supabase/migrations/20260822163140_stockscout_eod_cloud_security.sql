    check (jsonb_typeof(health_details) = 'object'),
  provenance jsonb not null default '{}'::jsonb
    check (jsonb_typeof(provenance) = 'object'),
  asset_hashes jsonb not null default '{}'::jsonb
    check (jsonb_typeof(asset_hashes) = 'object'),
