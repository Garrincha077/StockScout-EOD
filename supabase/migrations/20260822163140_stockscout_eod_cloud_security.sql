create or replace function public.eod_record_delivery_progress(
  p_user_id uuid,
  p_digest_type text,
  p_session_date date,
  p_content_hash text,
  p_part_count integer,
  p_last_part integer,
  p_completed boolean
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $function$
declare
  v_digest_key text;
  v_row public.eod_delivery_state%rowtype;
begin
  if p_user_id is null or p_session_date is null or p_completed is null
     or p_digest_type is null
     or p_digest_type not in ('daily', 'operational_error')
     or p_content_hash is null
     or p_content_hash !~ '^[0-9a-f]{64}$'
     or p_part_count is null or p_last_part is null
     or p_part_count < 1 or p_part_count > 100
     or p_last_part < 0 or p_last_part > p_part_count
     or (p_completed and p_last_part <> p_part_count) then
    raise exception 'invalid delivery progress' using errcode = '22023';
  end if;
  if not exists (
    select 1 from stockscout_private.eod_owners where user_id = p_user_id
  ) then
    raise exception 'delivery owner is not allowlisted' using errcode = '42501';
  end if;

  v_digest_key := p_digest_type || ':' || p_session_date::text;
  insert into public.eod_delivery_state (
    user_id, channel, digest_key, content_hash, total_parts,
    last_successful_part, completed_at, payload
  ) values (
    p_user_id, 'telegram', v_digest_key, p_content_hash, p_part_count,
    p_last_part, case when p_completed then now() end,
    jsonb_build_object(
      'digestType', p_digest_type,
      'sessionDate', p_session_date::text
    )
  )
  on conflict (user_id, channel, digest_key) do update set
    content_hash = excluded.content_hash,
    total_parts = excluded.total_parts,
    last_successful_part = case
      when eod_delivery_state.content_hash = excluded.content_hash
       and eod_delivery_state.total_parts = excluded.total_parts
      then greatest(
        eod_delivery_state.last_successful_part,
        excluded.last_successful_part
      )
      else excluded.last_successful_part
    end,
    completed_at = case
      when eod_delivery_state.content_hash = excluded.content_hash
       and eod_delivery_state.total_parts = excluded.total_parts
      then coalesce(eod_delivery_state.completed_at, excluded.completed_at)
      else excluded.completed_at
    end,
    payload = excluded.payload,
    updated_at = now()
  returning * into v_row;

  return jsonb_build_object(
    'digestType', p_digest_type,
    'sessionDate', p_session_date::text,
    'contentHash', v_row.content_hash,
    'partCount', v_row.total_parts,
    'lastPart', v_row.last_successful_part,
    'completed', v_row.completed_at is not null,
    'completedAt', v_row.completed_at,
    'updatedAt', v_row.updated_at
  );
end;
$function$;

create or replace function public.eod_get_delivery_state(
  p_user_id uuid,
  p_digest_type text,
  p_session_date date
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $function$
declare
  v_row public.eod_delivery_state%rowtype;
begin
  if p_user_id is null or p_session_date is null or p_digest_type is null
     or p_digest_type not in ('daily', 'operational_error') then
    raise exception 'invalid digest type' using errcode = '22023';
  end if;
  if not exists (
    select 1 from stockscout_private.eod_owners where user_id = p_user_id
  ) then
    raise exception 'delivery owner is not allowlisted' using errcode = '42501';
  end if;

  select * into v_row
  from public.eod_delivery_state
  where user_id = p_user_id
    and channel = 'telegram'
    and digest_key = p_digest_type || ':' || p_session_date::text;

  return jsonb_build_object(
    'digestType', p_digest_type,
    'sessionDate', p_session_date::text,
    'contentHash', v_row.content_hash,
    'partCount', coalesce(v_row.total_parts, 0),
    'lastPart', coalesce(v_row.last_successful_part, 0),
    'completed', v_row.completed_at is not null,
    'completedAt', v_row.completed_at,
    'updatedAt', v_row.updated_at
  );
end;
$function$;

