create or replace function stockscout_private.eod_is_owner()
returns boolean
language sql
stable
security definer
set search_path = ''
as $function$
  select
    (select auth.uid()) is not null
    and exists (
      select 1
      from stockscout_private.eod_owners o
      where o.user_id = (select auth.uid())
    );
$function$;

revoke all on function stockscout_private.eod_is_owner()
  from public, anon, authenticated, service_role;
grant execute on function stockscout_private.eod_is_owner()
  to authenticated, service_role;

-- Trusted publishers derive the one allowlisted owner from database state.
-- This avoids another long-lived owner identifier in Edge/GitHub configuration
-- and fails closed if project ownership ever becomes ambiguous.
create or replace function public.eod_single_owner_id()
returns uuid
language plpgsql
stable
security definer
set search_path = ''
as $function$
declare
  v_count integer;
  v_owner_id uuid;
begin
  select count(*), max(user_id::text)::uuid
  into v_count, v_owner_id
  from stockscout_private.eod_owners;
  if v_count <> 1 or v_owner_id is null then
    raise exception 'StockScout-EOD requires exactly one allowlisted owner'
      using errcode = '42501';
  end if;
  return v_owner_id;
end;
$function$;

revoke all on function public.eod_single_owner_id()
  from public, anon, authenticated, service_role;
grant execute on function public.eod_single_owner_id() to service_role;

