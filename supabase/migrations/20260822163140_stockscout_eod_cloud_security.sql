-- Reuse the single owner already proven by the private full-scan index. A
-- surprising multi-owner project aborts instead of silently broadening access;
-- a fresh project with no legacy table remains empty until explicitly seeded.
do $block$
declare
  v_owner_count integer;
  v_owner_id uuid;
begin
  if to_regclass('stockscout_private.full_scan_snapshots') is not null then
    execute
      'select count(distinct owner_id) from stockscout_private.full_scan_snapshots'
      into v_owner_count;
    if v_owner_count > 1 then
      raise exception
        'refusing to seed eod_owners: legacy full scan has % owners',
        v_owner_count;
    elsif v_owner_count = 1 then
      execute
        'select owner_id from stockscout_private.full_scan_snapshots limit 1'
        into v_owner_id;
      insert into stockscout_private.eod_owners (user_id)
      values (v_owner_id)
      on conflict (user_id) do nothing;
    end if;
  end if;
end;
$block$;

