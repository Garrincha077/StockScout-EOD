-- StockScout-EOD v1 public scan index and owner-scoped application state.
--
-- This migration is deliberately additive. It does not replace the existing
-- StockScout full_scan, stockscout_next, alert, or OAuth objects in the live
-- project. GitHub publishing reaches the write-only RPCs below exclusively
-- through the OIDC-verifying Edge Function.

create extension if not exists pgcrypto with schema extensions;

create schema if not exists stockscout_private;
-- Do not change existing schema grants: the live MCP already has private
-- StockScout objects here. Object-level grants below keep this migration
-- additive. USAGE alone exposes no table or function.
grant usage on schema stockscout_private to authenticated, service_role;

create table public.eod_scans (
  id bigint generated by default as identity primary key,
  run_id text not null unique check (run_id ~ '^[A-Za-z0-9._:-]{1,100}$'),
  scan_date date not null,
  market_data_date date not null,
  schema_version text not null check (schema_version = 'stockscout-eod/v1'),
  health_status text not null check (health_status in ('healthy', 'degraded')),
  candidate_count integer not null check (candidate_count >= 0),
  excluded_count integer not null check (excluded_count >= 0),
  record_count integer not null check (
    record_count >= 0 and record_count = candidate_count + excluded_count
  ),
  records_hash text not null check (records_hash ~ '^[0-9a-f]{64}$'),
  manifest_hash text not null check (manifest_hash ~ '^[0-9a-f]{64}$'),
  ranking_version text,
  detector_version text,
