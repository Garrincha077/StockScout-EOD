create or replace function public.eod_begin_publish(p_manifest jsonb)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $function$
declare
  v_upload_id uuid;
  v_candidate_count integer;
  v_excluded_count integer;
  v_record_count integer;
begin
  if jsonb_typeof(p_manifest) <> 'object'
     or coalesce(p_manifest->>'schemaVersion', '') <> 'stockscout-eod/v1'
     or coalesce(p_manifest->>'runId', '') !~ '^[A-Za-z0-9._:-]{1,100}$'
     or coalesce(p_manifest->>'scanDate', '') !~ '^[0-9]{4}-[0-9]{2}-[0-9]{2}$'
     or coalesce(p_manifest->>'marketDataDate', '') !~ '^[0-9]{4}-[0-9]{2}-[0-9]{2}$'
     or coalesce(p_manifest#>>'{health,status}', '') <> 'healthy'
     or coalesce(p_manifest#>>'{counts,candidates}', '') !~ '^[0-9]+$'
     or coalesce(p_manifest#>>'{counts,excluded}', '') !~ '^[0-9]+$'
     or coalesce(p_manifest#>>'{counts,total}', '') !~ '^[0-9]+$'
     or coalesce(p_manifest->>'recordsHash', '') !~ '^[0-9a-f]{64}$'
     or coalesce(p_manifest->>'manifestHash', '') !~ '^[0-9a-f]{64}$'
     or jsonb_typeof(coalesce(p_manifest->'assetHashes', '{}'::jsonb)) <> 'object'
     or jsonb_typeof(coalesce(p_manifest->'provenance', '{}'::jsonb)) <> 'object'
     or jsonb_typeof(coalesce(p_manifest->'fieldCatalog', '[]'::jsonb)) <> 'array'
  then
    raise exception 'invalid StockScout-EOD publish manifest'
      using errcode = '22023';
  end if;

  v_candidate_count := (p_manifest#>>'{counts,candidates}')::integer;
  v_excluded_count := (p_manifest#>>'{counts,excluded}')::integer;
  v_record_count := (p_manifest#>>'{counts,total}')::integer;
  if v_record_count < 1 or v_record_count > 100000
     or v_record_count <> v_candidate_count + v_excluded_count then
    raise exception 'manifest counts do not reconcile' using errcode = '22023';
  end if;

  delete from stockscout_private.eod_publish_uploads
  where created_at < now() - interval '24 hours';

  insert into stockscout_private.eod_publish_uploads (
    run_id, expected_count, expected_records_hash, manifest_hash, manifest
  ) values (
    p_manifest->>'runId', v_record_count, p_manifest->>'recordsHash',
    p_manifest->>'manifestHash', p_manifest
  )
  on conflict (run_id, manifest_hash) do update set
    expected_count = excluded.expected_count,
    expected_records_hash = excluded.expected_records_hash,
    manifest = excluded.manifest,
    status = 'uploading',
    updated_at = now()
  returning id into v_upload_id;

  -- A repeated begin starts a deterministic retry of the same immutable
  -- upload.  Clear partial rows while holding the upload row lock acquired by
  -- the upsert; append/finalize take the same lock, so stale wrapper metadata
  -- (especially scan_order or summary) cannot survive into a retry.
  delete from stockscout_private.eod_publish_records
  where upload_id = v_upload_id;

  return jsonb_build_object(
    'uploadId', v_upload_id,
    'runId', p_manifest->>'runId',
    'expectedCount', v_record_count
  );
end;
$function$;

create or replace function public.eod_append_publish_chunk(
  p_upload_id uuid,
  p_chunk_index integer,
  p_records jsonb
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $function$
declare
  v_received_count integer;
begin
  if p_chunk_index < 0
     or jsonb_typeof(p_records) <> 'array'
     or jsonb_array_length(p_records) < 1
     or jsonb_array_length(p_records) > 100 then
    raise exception 'invalid publish chunk' using errcode = '22023';
  end if;

  perform 1
  from stockscout_private.eod_publish_uploads
  where id = p_upload_id and status = 'uploading'
  for update;
  if not found then
    raise exception 'publish upload is missing or not writable'
      using errcode = '22023';
  end if;

  if exists (
    select 1
    from jsonb_array_elements(p_records) as r
    where coalesce(r->>'ticker', '') !~ '^[A-Z0-9._-]{1,20}$'
       or coalesce(r->>'source', '') not in ('candidate', 'excluded')
       or coalesce(r->>'scanOrder', '') !~ '^[0-9]+$'
       or coalesce(r->>'recordHash', '') !~ '^[0-9a-f]{64}$'
       or jsonb_typeof(r->'record') <> 'object'
       or jsonb_typeof(coalesce(r->'summary', '{}'::jsonb)) <> 'object'
  ) then
    raise exception 'invalid publish record' using errcode = '22023';
  end if;

  insert into stockscout_private.eod_publish_records (
    upload_id, chunk_index, ticker, source, scan_order,
    record_hash, record, summary
  )
  select
    p_upload_id,
    p_chunk_index,
    r->>'ticker',
    r->>'source',
    (r->>'scanOrder')::integer,
    r->>'recordHash',
    r->'record',
    coalesce(r->'summary', '{}'::jsonb)
  from jsonb_array_elements(p_records) as r
  on conflict (upload_id, ticker) do update set
    chunk_index = excluded.chunk_index,
    source = excluded.source,
    scan_order = excluded.scan_order,
    record_hash = excluded.record_hash,
    record = excluded.record,
    summary = excluded.summary;

  update stockscout_private.eod_publish_uploads
  set updated_at = now()
  where id = p_upload_id;

  select count(*) into v_received_count
  from stockscout_private.eod_publish_records
  where upload_id = p_upload_id;

  return jsonb_build_object(
    'uploadId', p_upload_id,
    'receivedCount', v_received_count
  );
end;
$function$;

create or replace function public.eod_finalize_publish(p_upload_id uuid)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $function$
declare
  v_upload stockscout_private.eod_publish_uploads%rowtype;
  v_count integer;
  v_hash text;
  v_scan_id bigint;
  v_existing_scan_id bigint;
  v_existing_hash text;
  v_previous_run_id text;
begin
  select * into v_upload
  from stockscout_private.eod_publish_uploads
  where id = p_upload_id
  for update;
  if not found then
    raise exception 'publish upload not found' using errcode = '22023';
  end if;

  select
    count(*),
    encode(
      extensions.digest(
        -- record_hash is the JCS-compatible SHA-256 of the complete wrapper
        -- {ticker, source, scanOrder, record, summary}, verified by the Edge
        -- Function before this service-role-only RPC is reached.
        coalesce(string_agg(record_hash, E'\n' order by source, ticker), ''),
        'sha256'
      ),
      'hex'
    )
  into v_count, v_hash
  from stockscout_private.eod_publish_records
  where upload_id = p_upload_id;

  if v_count <> v_upload.expected_count
     or v_hash <> v_upload.expected_records_hash then
    raise exception 'incomplete or corrupt publish: count %, hash %',
      v_count, v_hash using errcode = '22023';
  end if;

  select id, records_hash into v_existing_scan_id, v_existing_hash
  from public.eod_scans
  where run_id = v_upload.run_id;
  if found then
    if v_existing_hash <> v_hash then
      raise exception 'run id already exists with different content'
        using errcode = '23505';
    end if;
    delete from stockscout_private.eod_publish_uploads
    where id = p_upload_id;
    return jsonb_build_object(
      'scanId', v_existing_scan_id,
      'runId', v_upload.run_id,
      'recordCount', v_count,
      'recordsHash', v_hash,
      'idempotent', true
    );
  end if;

  update stockscout_private.eod_publish_uploads
  set status = 'finalizing', updated_at = now()
  where id = p_upload_id;

  select s.run_id into v_previous_run_id
  from public.eod_scan_state st
  join public.eod_scans s on s.id = st.active_scan_id
  where st.singleton;

  insert into public.eod_scans (
    run_id, scan_date, market_data_date, schema_version, health_status,
    candidate_count, excluded_count, record_count, records_hash,
    manifest_hash, ranking_version, detector_version, health_details,
    provenance, asset_hashes
  ) values (
    v_upload.manifest->>'runId',
    (v_upload.manifest->>'scanDate')::date,
    (v_upload.manifest->>'marketDataDate')::date,
    v_upload.manifest->>'schemaVersion',
    v_upload.manifest#>>'{health,status}',
    (v_upload.manifest#>>'{counts,candidates}')::integer,
    (v_upload.manifest#>>'{counts,excluded}')::integer,
    v_count,
    v_hash,
    v_upload.manifest->>'manifestHash',
    nullif(v_upload.manifest->>'rankingVersion', ''),
    nullif(v_upload.manifest->>'detectorVersion', ''),
    coalesce(v_upload.manifest->'health', '{}'::jsonb),
    coalesce(v_upload.manifest->'provenance', '{}'::jsonb),
    coalesce(v_upload.manifest->'assetHashes', '{}'::jsonb)
  ) returning id into v_scan_id;

  insert into public.eod_candidates (
    scan_id, document_id, ticker, source, scan_order, trade_status,
    primary_setup, risk_level, scan_price, entry_risk_pct, ranking_score,
    record, search_document, record_hash
  )
  select
    v_scan_id,
    'scan:' || v_upload.run_id || ':candidate:' || r.ticker,
    r.ticker,
    r.source,
    r.scan_order,
    coalesce(r.record#>>'{trade_plan,status}', r.record->>'trade_status'),
    coalesce(r.record->>'primary_setup', r.record->>'setup'),
    r.record->>'risk_level',
    case
      when coalesce(r.record->>'scan_price', r.record->>'price', '')
        ~ '^-?[0-9]+([.][0-9]+)?$'
      then coalesce(r.record->>'scan_price', r.record->>'price')::numeric
    end,
    case
      when coalesce(r.record#>>'{trade_plan,entry_risk_pct}', '')
        ~ '^-?[0-9]+([.][0-9]+)?$'
      then (r.record#>>'{trade_plan,entry_risk_pct}')::numeric
    end,
    case
      when coalesce(r.summary->>'rankingScore', r.record->>'headline_score', '')
        ~ '^-?[0-9]+([.][0-9]+)?$'
      then coalesce(r.summary->>'rankingScore', r.record->>'headline_score')::numeric
    end,
    r.record,
    to_tsvector('simple'::regconfig, r.ticker || ' ' || r.record::text),
    r.record_hash
  from stockscout_private.eod_publish_records r
  where r.upload_id = p_upload_id;

  insert into public.eod_candidate_history (
    scan_id, ticker, source, scan_order, trade_status, primary_setup,
    risk_level, scan_price, entry_risk_pct, ranking_score, summary
  )
  select
    c.scan_id, c.ticker, c.source, c.scan_order, c.trade_status,
    c.primary_setup, c.risk_level, c.scan_price, c.entry_risk_pct,
    c.ranking_score,
    jsonb_strip_nulls(r.summary || jsonb_build_object(
      'ticker', c.ticker,
      'source', c.source,
      'scanOrder', c.scan_order,
      'tradeStatus', c.trade_status,
      'primarySetup', c.primary_setup,
      'riskLevel', c.risk_level,
      'scanPrice', c.scan_price,
      'entryRiskPct', c.entry_risk_pct,
      'rankingScore', c.ranking_score
    ))
  from public.eod_candidates c
  join stockscout_private.eod_publish_records r
    on r.upload_id = p_upload_id and r.ticker = c.ticker
  where c.scan_id = v_scan_id;

  insert into public.eod_scan_fields (
    scan_id, field_path, scalar_types, populated_count, example
  )
  select
    v_scan_id,
    field->>'field',
    array(
      select jsonb_array_elements_text(coalesce(field->'types', '[]'::jsonb))
    ),
    case when coalesce(field->>'count', '') ~ '^[0-9]+$'
      then (field->>'count')::integer else 0 end,
    field->'example'
  from jsonb_array_elements(
    coalesce(v_upload.manifest->'fieldCatalog', '[]'::jsonb)
  ) as field
  where coalesce(field->>'field', '')
    ~ '^[A-Za-z0-9_-]+(\.[A-Za-z0-9_-]+)*$'
    and jsonb_typeof(coalesce(field->'types', '[]'::jsonb)) = 'array';

  insert into public.eod_scan_state (singleton, active_scan_id, updated_at)
  values (true, v_scan_id, now())
  on conflict (singleton) do update set
    active_scan_id = excluded.active_scan_id,
    updated_at = excluded.updated_at;

  -- Only the activated scan retains complete records and the field catalog.
  delete from public.eod_candidates where scan_id <> v_scan_id;
  delete from public.eod_scan_fields where scan_id <> v_scan_id;

  -- A rerun replaces the same market session, then history is capped at the
  -- latest 252 sessions. Alert events deliberately keep their textual run id.
  delete from public.eod_scans
  where scan_date = (v_upload.manifest->>'scanDate')::date
    and id <> v_scan_id;
  delete from public.eod_scans
  where id in (
    select id
    from public.eod_scans
    where id <> v_scan_id
    order by scan_date desc, published_at desc, id desc
    offset 251
  );

  delete from stockscout_private.eod_publish_uploads
  where id = p_upload_id;

  return jsonb_build_object(
    'scanId', v_scan_id,
    'runId', v_upload.run_id,
    'recordCount', v_count,
    'recordsHash', v_hash,
    'previousRunId', v_previous_run_id,
    'idempotent', false
  );
end;
$function$;

